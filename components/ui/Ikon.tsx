export type NamaIkon = keyof typeof IKON;

export default function Ikon({
  nama,
  className = 'size-5',
  isi = false,
}: {
  nama: NamaIkon;
  className?: string;
  isi?: boolean;
}) {
  const Komponen = IKON[nama];
  return <Komponen className={`shrink-0 ${className}`} fill={isi ? 'currentColor' : 'none'} strokeWidth={1.75} aria-hidden="true" />;
}
